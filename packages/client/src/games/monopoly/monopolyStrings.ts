export type MpKey = keyof typeof TR;

export function makeMpT(language: Language) {
  const table: Record<MpKey, string> = language === 'en' ? EN : TR;
  return (key: MpKey, vars?: Record<string, string | number>): string => {
    let text: string = table[key];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
}
